/*
 * Snapshot (characterization) tests of the error responses to invalid requests: query params, headers, payloads
 *  and routes.
 *
 * The complete payload of each response, including the error messages generated by joi and hapi, is compared with
 *  test/unit/snapshots/sthHttpValidation.json, recorded with the code previous to the dependency upgrades on
 *  Node.js 14. The messages are expected to change when upgrading hapi and joi: in that case, record the snapshots
 *  again (see test/unit/sthSnapshot.js) and explain the changes. Each test is independent from the rest.
 */

const ROOT_PATH = require('app-root-path');
const sthConfig = require(ROOT_PATH + '/lib/configuration/sthConfiguration');
const sthDatabase = require(ROOT_PATH + '/lib/database/sthDatabase');
const sthDatabaseNaming = require(ROOT_PATH + '/lib/database/model/sthDatabaseNaming');
const sthServer = require(ROOT_PATH + '/lib/server/sthServer');
const sthConfigurationPin = require(ROOT_PATH + '/test/unit/sthConfigurationPin');
const sthHttpTestClient = require(ROOT_PATH + '/test/unit/sthHttpTestClient');
const sthSnapshot = require(ROOT_PATH + '/test/unit/sthSnapshot');
const path = require('path');

const SERVICE_HEADERS = { 'Fiware-Service': 'sthvalidation', 'Fiware-ServicePath': '/validation' };
const V1_PATH = '/STH/v1/contextEntities/type/T/id/E1/attributes/temperature';
const V2_PATH = '/STH/v2/entities/E1/attrs/temperature';

/**
 * Returns a GET request to the NGSIv1 API
 * @param {String} query The query string
 * @return {Object} The request
 */
function getV1(query) {
    return { method: 'GET', path: V1_PATH + '?' + query, headers: SERVICE_HEADERS };
}

/**
 * Returns a GET request to the NGSIv2 API
 * @param {String} query The query string
 * @return {Object} The request
 */
function getV2(query) {
    return { method: 'GET', path: V2_PATH + '?' + query, headers: SERVICE_HEADERS };
}

/**
 * Returns the headers to send without the one provided
 * @param {String} name The name of the header to leave out
 * @return {Object} The headers
 */
function withoutHeader(name) {
    const headers = Object.assign({}, SERVICE_HEADERS);
    delete headers[name];
    return headers;
}

/**
 * Returns an NGSIv1 notification without attributes
 * @return {Object} The notification body
 */
function getNotificationWithoutAttributes() {
    return {
        subscriptionId: '1234567890ABCDF123456789',
        originator: 'orion.contextBroker.instance',
        contextResponses: [
            {
                contextElement: { attributes: [], type: 'T', isPattern: 'false', id: 'E1' },
                statusCode: { code: '200', reasonPhrase: 'OK' }
            }
        ]
    };
}

/**
 * Returns the invalid requests whose responses are compared with their snapshots
 * @return {Object} The requests by name
 */
function getRequests() {
    return {
        v1NoQuery: getV1(''),
        v1LastNNegative: getV1('lastN=-1'),
        v1LastNNotANumber: getV1('lastN=abc'),
        v1LastNDecimal: getV1('lastN=1.5'),
        v1LastNOverMaxPageSize: getV1('lastN=101'),
        v1HLimitNegative: getV1('hLimit=-1&hOffset=0'),
        v1HOffsetNegative: getV1('hLimit=1&hOffset=-1'),
        v1HLimitWithoutHOffset: getV1('hLimit=1'),
        v1HLimitOverMaxPageSize: getV1('hLimit=101&hOffset=0'),
        v1HLimitGreaterThanLastN: getV1('lastN=2&hLimit=3&hOffset=0'),
        v1AggrMethodInvalid: getV1('aggrMethod=avg&aggrPeriod=hour'),
        v1AggrMethodListInvalid: getV1('aggrMethod=sum,avg&aggrPeriod=hour'),
        v1AggrPeriodInvalid: getV1('aggrMethod=sum&aggrPeriod=week'),
        v1AggrMethodWithoutAggrPeriod: getV1('aggrMethod=sum'),
        v1DateFromInvalid: getV1('lastN=1&dateFrom=notADate'),
        v1DateToInvalid: getV1('lastN=1&dateTo=2026-13-45'),
        v1CountInvalid: getV1('lastN=1&count=maybe'),
        v1UnknownQueryParam: getV1('lastN=1&foo=bar'),
        v1MissingService: { method: 'GET', path: V1_PATH + '?lastN=1', headers: withoutHeader('Fiware-Service') },
        v1MissingServicePath: {
            method: 'GET',
            path: V1_PATH + '?lastN=1',
            headers: withoutHeader('Fiware-ServicePath')
        },
        v2MissingType: { method: 'GET', path: V2_PATH + '?lastN=1', headers: SERVICE_HEADERS },
        v2NoQuery: getV2('type=T'),
        v2LastNNegative: getV2('type=T&lastN=-1'),
        v2HLimitGreaterThanLastN: getV2('type=T&lastN=2&hLimit=3&hOffset=0'),
        v2AggrMethodInvalid: getV2('type=T&aggrMethod=avg&aggrPeriod=hour'),
        v2AggrPeriodInvalid: getV2('type=T&aggrMethod=sum&aggrPeriod=week'),
        v2DateFromInvalid: getV2('type=T&lastN=1&dateFrom=notADate'),
        v2MissingService: {
            method: 'GET',
            path: V2_PATH + '?type=T&lastN=1',
            headers: withoutHeader('Fiware-Service')
        },
        notifyWithoutAttributes: {
            method: 'POST',
            path: '/notify',
            headers: SERVICE_HEADERS,
            body: getNotificationWithoutAttributes()
        },
        notifyMissingService: {
            method: 'POST',
            path: '/notify',
            headers: withoutHeader('Fiware-Service'),
            body: getNotificationWithoutAttributes()
        },
        notifyMissingServicePath: {
            method: 'POST',
            path: '/notify',
            headers: withoutHeader('Fiware-ServicePath'),
            body: getNotificationWithoutAttributes()
        },
        deleteMissingService: {
            method: 'DELETE',
            path: '/STH/v1/contextEntities/type/T/id/E1',
            headers: withoutHeader('Fiware-Service')
        },
        setLogLevelInvalid: { method: 'PUT', path: '/admin/log?level=VERBOSE' },
        setLogLevelMissing: { method: 'PUT', path: '/admin/log' },
        unknownRoute: { method: 'GET', path: '/unknown/route' },
        unsupportedMethod: { method: 'PATCH', path: V1_PATH + '?lastN=1', headers: SERVICE_HEADERS }
    };
}

describe('HTTP API validation snapshots', function () {
    let restoreConfiguration;

    before(function () {
        // The responses depend on the data model and the naming of the collections
        restoreConfiguration = sthConfigurationPin.pinInitialConfiguration();
    });

    after(function () {
        restoreConfiguration();
    });

    const matcher = sthSnapshot.createMatcher(path.join(__dirname, 'snapshots', 'sthHttpValidation.json'));
    const requests = getRequests();

    before(function (done) {
        // No request is expected to reach the database, but the connection is established in case any of them does
        sthDatabase.connect(
            {
                authentication: sthConfig.DB_AUTHENTICATION,
                dbURI: sthConfig.DB_URI,
                replicaSet: sthConfig.REPLICA_SET,
                database: sthDatabaseNaming.getDatabaseName(sthConfig.DEFAULT_SERVICE),
                poolSize: sthConfig.POOL_SIZE
            },
            function (err) {
                if (err) {
                    return done(err);
                }
                return sthServer.startServer(sthConfig.STH_HOST, sthConfig.STH_PORT, function (err) {
                    done(err);
                });
            }
        );
    });

    after(function (done) {
        matcher.save();
        sthServer.stopServer(function () {
            sthDatabase.closeConnection(function () {
                done();
            });
        });
    });

    Object.keys(requests).forEach(function (name) {
        const request = requests[name];
        it(name + ': ' + request.method + ' ' + request.path, function (done) {
            sthHttpTestClient.sendRequest(
                {
                    method: request.method,
                    path: request.path,
                    headers: Object.assign({ 'Fiware-Correlator': 'validation-' + name }, request.headers),
                    body: request.body
                },
                sthHttpTestClient.assertResponse(done, function (err, response) {
                    matcher.match(name, sthSnapshot.toSnapshot(request, err, response));
                })
            );
        });
    });
});
