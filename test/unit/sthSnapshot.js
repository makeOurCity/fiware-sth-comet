/*
 * Snapshot (characterization) testing support.
 *
 * HTTP responses are reduced to their status code, their relevant headers and their body, the values which change
 *  from run to run or depend on the environment are replaced by placeholders, and the result is compared with the
 *  snapshot stored in a JSON file under test/unit/snapshots/.
 *
 * The snapshots were recorded with the code previous to the upgrade of its dependencies running on Node.js 14, so
 *  that the tests detect any change in the behaviour of the API. To record them again after an intended change, run
 *  the tests with the UPDATE_SNAPSHOTS=1 environment variable and review the diff of the snapshot files:
 *
 *      UPDATE_SNAPSHOTS=1 npm test
 */

const assert = require('assert');
const fs = require('fs');

// Headers which do not depend on the run and are part of the API behaviour. The rest of them (date, connection,
//  vary, cache-control...) are left out
const RELEVANT_HEADERS = ['content-type', 'content-disposition', 'fiware-correlator', 'fiware-total-count'];

const UUID_REGEXP = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const OBJECT_ID_REGEXP = /^[0-9a-f]{24}$/i;
// Name of the generated CSV files: <attrName>-<Date.now()>-<counter>.csv
const CSV_FILE_NAME_REGEXP = /-\d+-\d+\.csv$/;
// Time zone name of the dates formatted by Date#toString(), such as the ones of the CSV files, which depends on the
//  locale: "GMT+0000 (Coordinated Universal Time)" or "GMT+0000 (協定世界時)", for example
const TIME_ZONE_NAME_REGEXP = /(GMT[+-]\d{4}) \([^)]*\)/g;

/**
 * Returns true if the header is relevant for the snapshots
 * @param {String} name The header name, in lower case
 * @return {Boolean} True if relevant
 */
function isRelevantHeader(name) {
    return RELEVANT_HEADERS.indexOf(name) !== -1 || name.indexOf('access-control-') === 0;
}

/**
 * Replaces the values of a header which change from run to run by placeholders
 * @param {String} name The header name, in lower case
 * @param {String} value The header value
 * @return {String} The normalized value
 */
function normalizeHeaderValue(name, value) {
    if (name === 'fiware-correlator' && UUID_REGEXP.test(value)) {
        // Correlator generated by the server since the request did not include one
        return '<uuid>';
    }
    if (name === 'content-disposition') {
        return value.replace(CSV_FILE_NAME_REGEXP, '-<timestamp>-<counter>.csv');
    }
    return value;
}

/**
 * Returns the relevant headers of a response, normalized and sorted by name
 * @param {Object} headers The response headers, as returned by the Node.js http module
 * @return {Object} The relevant headers
 */
function pickHeaders(headers) {
    const result = {};
    Object.keys(headers)
        .filter(isRelevantHeader)
        .sort()
        .forEach(function (name) {
            result[name] = normalizeHeaderValue(name, headers[name]);
        });
    return result;
}

/**
 * Replaces recursively the ObjectIds included in a parsed JSON value by a placeholder
 * @param {*} value The value
 * @return {*} The normalized value
 */
function replaceObjectIds(value) {
    if (Array.isArray(value)) {
        return value.map(replaceObjectIds);
    }
    if (value && typeof value === 'object') {
        const result = {};
        Object.keys(value).forEach(function (key) {
            result[key] = replaceObjectIds(value[key]);
        });
        return result;
    }
    if (typeof value === 'string' && OBJECT_ID_REGEXP.test(value)) {
        return '<ObjectId>';
    }
    return value;
}

/**
 * Returns the body of a response ready to be compared: JSON bodies are parsed and normalized, the rest of them are
 *  kept as strings replacing the time zone names of the dates
 * @param {String} body The response body
 * @param {String} contentType The content-type header of the response, if any
 * @return {*} The normalized body
 */
function normalizeBody(body, contentType) {
    if (body && contentType && contentType.indexOf('application/json') === 0) {
        return replaceObjectIds(JSON.parse(body));
    }
    return body.replace(TIME_ZONE_NAME_REGEXP, '$1 (<time zone name>)');
}

/**
 * Returns the normalized representation of a response used in the snapshots
 * @param {Object} response The response as returned by sthHttpTestClient.sendRequest()
 * @return {Object} The status code, the relevant headers and the normalized body
 */
function normalizeResponse(response) {
    return {
        statusCode: response.statusCode,
        headers: pickHeaders(response.headers),
        body: normalizeBody(response.body, response.headers['content-type'])
    };
}

/**
 * Returns the snapshot of a request and its result
 * @param {Object} request The request, including its method and path
 * @param {Error} err The error returned by sthHttpTestClient.sendRequest(), if any
 * @param {Object} response The response returned by sthHttpTestClient.sendRequest(), if any
 * @return {Object} The request and the normalized response, or the ETIMEDOUT error if no complete response was
 *  received in time (which is the current behaviour of some requests)
 */
function toSnapshot(request, err, response) {
    const snapshot = { request: request.method + ' ' + request.path };
    if (err) {
        if (err.code !== 'ETIMEDOUT') {
            throw err;
        }
        snapshot.error = err.code;
    } else {
        snapshot.response = normalizeResponse(response);
    }
    return snapshot;
}

/**
 * Returns true if the snapshots should be recorded instead of compared
 * @param {Object} env The environment variables
 * @return {Boolean} True if UPDATE_SNAPSHOTS is set to 1 or true
 */
function isUpdateMode(env) {
    return env.UPDATE_SNAPSHOTS === '1' || env.UPDATE_SNAPSHOTS === 'true';
}

/**
 * Reads the snapshots stored in a file
 * @param {String} file The snapshot file path
 * @return {Object} The snapshots by key, empty if the file does not exist
 */
function loadSnapshots(file) {
    if (!fs.existsSync(file)) {
        return {};
    }
    return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/**
 * Returns a matcher comparing values with the snapshots stored in a file or, in update mode, recording them
 * @param {String} file The snapshot file path
 * @param {Boolean} updateMode True to record the values instead of comparing them (isUpdateMode() by default)
 * @return {Object} An object including the following functions:
 *  - match(key, actual): throws an AssertionError if the actual value differs from the snapshot stored for the key
 *  - save(): writes the recorded values to the file in update mode, keeping the snapshots not recorded again
 */
function createMatcher(file, updateMode) {
    const isUpdating = updateMode === undefined ? isUpdateMode(process.env) : updateMode;
    const snapshots = loadSnapshots(file);

    function match(key, actual) {
        if (isUpdating) {
            snapshots[key] = actual;
            return;
        }
        if (!Object.prototype.hasOwnProperty.call(snapshots, key)) {
            throw new assert.AssertionError({
                message: 'No snapshot "' + key + '" in ' + file + '. Run the tests with UPDATE_SNAPSHOTS=1 to record it'
            });
        }
        try {
            assert.deepStrictEqual(actual, snapshots[key]);
        } catch (err) {
            throw new assert.AssertionError({
                message:
                    'Snapshot "' +
                    key +
                    '" does not match\nExpected:\n' +
                    JSON.stringify(snapshots[key], null, 2) +
                    '\nActual:\n' +
                    JSON.stringify(actual, null, 2)
            });
        }
    }

    function save() {
        if (isUpdating) {
            fs.writeFileSync(file, JSON.stringify(snapshots, null, 2) + '\n');
        }
    }

    return {
        match,
        save
    };
}

module.exports = {
    pickHeaders,
    normalizeBody,
    normalizeResponse,
    toSnapshot,
    isUpdateMode,
    createMatcher
};
